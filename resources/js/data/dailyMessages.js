const DAY_MS = 24 * 60 * 60 * 1000;

/**
 * Un mensaje por dia, el mismo durante todo el dia y para todos los equipos:
 * se elige por el numero de dias desde 1970 de la fecha local (`YYYY-MM-DD`),
 * asi recorre la lista entera antes de repetir.
 */
export function messageOfTheDay(isoDate) {
    const [year, month, day] = String(isoDate).split('-').map(Number);
    const dayNumber = Math.floor(Date.UTC(year, month - 1, day) / DAY_MS);
    const length = DAILY_MESSAGES.length;

    return DAILY_MESSAGES[((dayNumber % length) + length) % length];
}
